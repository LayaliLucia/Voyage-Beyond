#!/usr/bin/env node
/**
 * Refreshes data/snapshot.js with REAL data from NASA's public APIs.
 *
 *   node scripts/fetch-nasa-data.mjs                 # uses DEMO_KEY (rate limited)
 *   NASA_API_KEY=yourkey node scripts/fetch-nasa-data.mjs   # free key: https://api.nasa.gov
 *
 * Requires Node 18+ (built-in fetch). Run it before deploying so the offline fallback
 * the game uses is real NASA data instead of the hand-written reference events.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const KEY = process.env.NASA_API_KEY || 'DEMO_KEY';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ymd = d => d.toISOString().slice(0, 10);
const getJSON = async (url) => { const r = await fetch(url, { headers: { Accept: 'application/json' } }); if (!r.ok) throw new Error(`${r.status} ${url}`); return r.json(); };

const prev = readFileSync(join(root, 'data/snapshot.js'), 'utf8');
const sandbox = { window: {} }; sandbox.window.VB = {};
vm.runInNewContext(prev.replace(/^\s*window\.VB = window\.VB \|\| \{\};/m, ''), { window: sandbox.window, VB: sandbox.window.VB });
const radiation = sandbox.window.VB.snapshot.radiation;

/* ---- DONKI: coronal mass ejections + solar flares (last 90 days) ---- */
const now = new Date(), start = new Date(now - 90 * 864e5);
const q = `startDate=${ymd(start)}&endDate=${ymd(now)}&api_key=${KEY}`;
console.log('Fetching DONKI CME + FLR...');
const cmeRaw = await getJSON(`https://api.nasa.gov/DONKI/CME?${q}`);
const cmes = cmeRaw.map(e => {
    const list = e.cmeAnalyses || [], a = list.find(x => x.isMostAccurate) || list[0];
    if (!a || !a.speed) return null;
    return { id: e.activityID, time: e.startTime, src: e.sourceLocation || 'unknown', speed: Math.round(a.speed), type: a.type || '?', half: a.halfAngle, note: (e.note || '').replace(/\s+/g, ' ').slice(0, 170), live: true };
}).filter(Boolean).sort((a, b) => b.speed - a.speed);
if (cmes.length < 3) throw new Error('Fewer than 3 CMEs with speeds in the window');
const pick = [cmes[0], cmes[Math.floor(cmes.length / 2)], cmes[cmes.length - 1], cmes[Math.floor(cmes.length / 4)], cmes[Math.floor(cmes.length * 0.75)]].filter((v, i, a) => v && a.indexOf(v) === i);
const flrRaw = await getJSON(`https://api.nasa.gov/DONKI/FLR?${q}`);
const flares = flrRaw.filter(f => f.classType).sort((a, b) => (b.beginTime > a.beginTime ? 1 : -1)).slice(0, 5)
    .map(f => ({ id: f.flrID, time: (f.beginTime || '').slice(0, 10), cls: f.classType, src: f.sourceLocation || '', live: true }));

/* ---- OSDR: plant spaceflight studies ---- */
let osdr = [];
try {
    console.log('Fetching OSDR studies...');
    const raw = await getJSON('https://osdr.nasa.gov/osdr/data/search?term=plant%20spaceflight&type=cgene&from=0&size=6');
    osdr = ((raw.hits && raw.hits.hits) || []).map(h => { const s = h._source || h; const title = s['Study Title'] || s.title; return title ? { title: String(title).slice(0, 120), id: String(s['Study Identifier'] || h._id || ''), note: '', live: true } : null; }).filter(Boolean);
} catch (e) { console.warn('OSDR fetch failed (' + e.message + '); keeping reference studies.'); }
if (!osdr.length) osdr = [
    { title: 'Veggie plant growth on the ISS (red romaine lettuce, zinnias)', id: null, note: 'Astronauts grew and ate lettuce in 2015 and bloomed zinnias in 2016 using red + blue LED light.' },
    { title: 'Plant Habitat-04: chile peppers grown on the ISS', id: null, note: 'Hatch chile peppers were grown and harvested on the ISS in 2021.' }
];

const out = `/* Generated by scripts/fetch-nasa-data.mjs on ${ymd(now)} from live NASA APIs (DONKI, OSDR). */
window.VB = window.VB || {};
VB.snapshot = ${JSON.stringify({ source: 'nasa-api', generated: ymd(now), cmes: pick, flares, osdr, radiation }, null, 4)};
`;
writeFileSync(join(root, 'data/snapshot.js'), out);
console.log(`Wrote data/snapshot.js: ${pick.length} CMEs, ${flares.length} flares, ${osdr.length} OSDR studies.`);
